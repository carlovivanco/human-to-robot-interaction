"""Writes sim_ros2/assets/hand/ (model.sdf + hand.glb): a static 3D open hand for the simulated person.

The hand is a puffy relief mesh: the silhouette of a real open-palm photo (assets/hand.png, see assets/CREDITS.txt)
is cut out with MediaPipe landmarks + GrabCut, inflated into a dome and textured with the photo. A hand built only from
capsules was never recognised as Open_Palm by MediaPipe, a photographic texture is.

  python3 scripts/make_hand_relief.py
Needs opencv, mediapipe, scipy, trimesh (venv of panda_ws). Palm normal +x, fingers +z, origin at the palm centre.
"""
import cv2
import mediapipe as mp
import numpy as np
import trimesh
from PIL import Image
from mediapipe.tasks import python
from mediapipe.tasks.python import vision
from scipy.ndimage import distance_transform_edt

SRC, OUT = "sim_ros2/assets/hand.png", "sim_ros2/assets/hand"
METRES_PER_PX = 0.00045  # 420 px from fingertip to palm base = 19 cm
DOME = 0.030  # height of the dome over the palm centre (m)
STEP = 3  # grid pixels per mesh cell

img = cv2.imread(SRC)
rec = vision.GestureRecognizer.create_from_options(vision.GestureRecognizerOptions(
    base_options=python.BaseOptions(model_asset_path="vision_sim/models/gesture_recognizer.task"),
    running_mode=vision.RunningMode.IMAGE))
res = rec.recognize(mp.Image(image_format=mp.ImageFormat.SRGB, data=np.ascontiguousarray(cv2.cvtColor(img, cv2.COLOR_BGR2RGB))))
h, w = img.shape[:2]
lm = np.array([[p.x * w, p.y * h] for p in res.hand_landmarks[0]])

hull = np.zeros((h, w), np.uint8)
cv2.fillConvexPoly(hull, cv2.convexHull(lm.astype(np.int32)), 255)
gc = np.full((h, w), cv2.GC_BGD, np.uint8)
gc[cv2.dilate(hull, np.ones((45, 45))) > 0] = cv2.GC_PR_BGD
gc[hull > 0] = cv2.GC_PR_FGD
gc[cv2.erode(hull, np.ones((15, 15))) > 0] = cv2.GC_FGD
cv2.grabCut(img, gc, None, np.zeros((1, 65)), np.zeros((1, 65)), 8, cv2.GC_INIT_WITH_MASK)
mask = np.where((gc == 1) | (gc == 3), 255, 0).astype(np.uint8)
hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
mask[hsv[..., 1] < 55] = 0  # skin is saturated, the grey wall between the fingers is not
mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((5, 5)))
n, lab, st, _ = cv2.connectedComponentsWithStats(mask)
mask = (lab == 1 + np.argmax(st[1:, cv2.CC_STAT_AREA])).astype(np.uint8) * 255
mask = cv2.erode(mask, np.ones((3, 3)))  # keep the background colour out of the texture

dist = distance_transform_edt(mask > 0)
height = DOME * np.sqrt(np.clip(dist / dist.max(), 0, 1))  # steep at the edge, flat on top
cu, cv_ = lm[:, 0].mean(), (lm[0, 1] + lm[9, 1]) / 2  # palm centre: between the wrist and the middle knuckle

ys, xs = np.mgrid[0:h:STEP, 0:w:STEP]
idx = -np.ones(ys.shape, int)
inside = mask[ys, xs] > 0
idx[inside] = np.arange(inside.sum())
vx, vy = xs[inside], ys[inside]
front = np.stack([height[vy, vx], (vx - cu) * METRES_PER_PX, (cv_ - vy) * METRES_PER_PX], 1)
nv = len(front)
back = front.copy(); back[:, 0] = -0.004  # flat back, slightly behind the palm plane
uv = np.stack([vx / w, 1 - vy / h], 1)

faces = []
for r in range(ys.shape[0] - 1):
    for c in range(xs.shape[1] - 1):
        a, b, d, e = idx[r, c], idx[r, c + 1], idx[r + 1, c], idx[r + 1, c + 1]
        for t in ((a, d, b), (b, d, e)):  # counter-clockwise seen from +x (the camera side)
            if min(t) >= 0:
                faces.append(t)
# side skirt: boundary edges of the front surface down to the back
edges = {}
for t in faces:
    for i in range(3):
        k = (t[i], t[(i + 1) % 3]); edges[k] = edges.get(k, 0) + 1
skirt = [(p, q) for (p, q) in edges if (q, p) not in edges]

# the texture travels inside the .glb (no axis conversion: Gazebo takes the coordinates as they are)
verts = np.vstack([front, back])
mesh = trimesh.Trimesh(
    vertices=verts,
    faces=np.array(faces + [(p, q, q + nv) for p, q in skirt] + [(p, q + nv, p + nv) for p, q in skirt]),
    visual=trimesh.visual.TextureVisuals(uv=np.vstack([uv, uv]), material=trimesh.visual.material.PBRMaterial(
        baseColorTexture=Image.open(SRC), metallicFactor=0.0, roughnessFactor=1.0)),  # matt: metallic would render black
    process=False)
mesh.export(f"{OUT}/hand.glb")
open(f"{OUT}/model.sdf", "w").write("""<?xml version="1.0"?>
<!-- generated by scripts/make_hand_relief.py -->
<sdf version="1.9">
  <model name="hand">
    <static>true</static>
    <link name="link">
      <collision name="palm"><pose>0.011 0 0.02 0 0 0</pose><geometry><box><size>0.03 0.12 0.20</size></box></geometry>
        <surface><friction><ode><mu>1.5</mu><mu2>1.5</mu2></ode></friction></surface></collision>
      <visual name="v"><geometry><mesh><uri>hand.glb</uri></mesh></geometry></visual>
    </link>
  </model>
</sdf>
""")
print(f"{nv} vertices, {len(faces)} faces, {len(skirt)} skirt edges")
